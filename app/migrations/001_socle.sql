-- Socle : paramètres de l'installation, membres, pages libres

CREATE TABLE IF NOT EXISTS parametre (
    cle VARCHAR(100) PRIMARY KEY,
    valeur TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS membre (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    email VARCHAR(190) NOT NULL UNIQUE,
    prenom VARCHAR(100) NOT NULL DEFAULT '',
    nom VARCHAR(100) NOT NULL DEFAULT '',
    est_admin TINYINT(1) NOT NULL DEFAULT 0,
    cree_le DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS page (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    slug VARCHAR(100) NOT NULL UNIQUE,
    titre VARCHAR(200) NOT NULL,
    contenu TEXT NOT NULL,
    publiee TINYINT(1) NOT NULL DEFAULT 0,
    dans_menu TINYINT(1) NOT NULL DEFAULT 0,
    ordre INT NOT NULL DEFAULT 50,
    modifiee_le DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
